/// The fixture tables are shared, so tests that create them run one at a time.
static FIXTURE: Mutex<()> = Mutex::new(());

fn current_user(conn: &mut OracleConnection) -> String {
    let row = single_row(conn, "SELECT USER AS u FROM dual");
    row.column(0).as_string::<i32>().value(0).to_string()
}

fn setup(conn: &mut OracleConnection) {
    for table in ["ORKIDEA_C_CHILD", "ORKIDEA_C_PARENT", "ORKIDEA_C_TEMP"] {
        drop_table(conn, table);
    }
    exec(
        conn,
        "CREATE OR REPLACE VIEW orkidea_c_view AS SELECT 1 AS one FROM dual",
    );
    exec(
        conn,
        "CREATE TABLE orkidea_c_parent (
            id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
            code VARCHAR2(20 CHAR) NOT NULL,
            region CHAR(2),
            amount NUMBER(12,2) DEFAULT 0,
            doubled NUMBER GENERATED ALWAYS AS (amount * 2) VIRTUAL,
            created TIMESTAMP(3),
            CONSTRAINT orkidea_c_parent_pk PRIMARY KEY (id, region),
            CONSTRAINT orkidea_c_parent_code_uk UNIQUE (code),
            CONSTRAINT orkidea_c_parent_amount_ck CHECK (amount >= 0)
        )",
    );
    exec(
        conn,
        "COMMENT ON COLUMN orkidea_c_parent.code IS 'Business key'",
    );
    exec(
        conn,
        "CREATE TABLE orkidea_c_child (
            child_id NUMBER(10) PRIMARY KEY,
            parent_id NUMBER(10),
            parent_region CHAR(2),
            CONSTRAINT orkidea_c_child_fk FOREIGN KEY (parent_id, parent_region)
                REFERENCES orkidea_c_parent (id, region)
        )",
    );
    exec(
        conn,
        "CREATE GLOBAL TEMPORARY TABLE orkidea_c_temp (x NUMBER) ON COMMIT PRESERVE ROWS",
    );
}

fn objects(
    conn: &OracleConnection,
    depth: ObjectDepth,
    schema: Option<&str>,
    table: Option<&str>,
    types: Option<Vec<&str>>,
    column: Option<&str>,
) -> RecordBatch {
    let reader = conn
        .get_objects(depth, None, schema, table, types, column)
        .unwrap();
    let batches: Vec<RecordBatch> = reader.collect::<Result<_, _>>().unwrap();
    assert_eq!(batches.len(), 1);
    batches[0].clone()
}

fn list_item(array: &dyn Array, index: usize) -> Option<StructArray> {
    let list = array.as_list::<i32>();
    if list.is_null(index) {
        return None;
    }
    Some(list.value(index).as_struct().clone())
}

fn strings(array: &StructArray, name: &str) -> Vec<String> {
    let column = array.column_by_name(name).unwrap().as_string::<i32>();
    (0..column.len())
        .map(|i| column.value(i).to_string())
        .collect()
}

fn find(array: &StructArray, name_field: &str, name: &str) -> usize {
    strings(array, name_field)
        .iter()
        .position(|n| n == name)
        .unwrap_or_else(|| panic!("{name} not found in {name_field}"))
}

/// Tables of `schema` in a GetObjects result.
fn tables_of(batch: &RecordBatch, schema: &str) -> Option<StructArray> {
    let schemas = list_item(batch.column(1).as_ref(), 0).unwrap();
    let index = find(&schemas, "db_schema_name", schema);
    list_item(
        schemas.column_by_name("db_schema_tables").unwrap().as_ref(),
        index,
    )
}

#[test]
fn catalogs_depth_reports_the_container() {
    let Some(mut conn) = connect() else { return };
    let batch = objects(&conn, ObjectDepth::Catalogs, None, None, None, None);
    assert_eq!(batch.num_rows(), 1);
    let name = batch.column(0).as_string::<i32>().value(0).to_string();
    let expected = single_row(
        &mut conn,
        "SELECT SYS_CONTEXT('USERENV', 'CON_NAME') AS c FROM dual",
    );
    assert_eq!(name, expected.column(0).as_string::<i32>().value(0));
    assert!(
        batch.column(1).is_null(0),
        "schemas must be null at depth catalogs"
    );

    // The catalog filter is a search pattern.
    let reader = conn
        .get_objects(ObjectDepth::All, Some("NO_SUCH_%"), None, None, None, None)
        .unwrap();
    let total: usize = reader.map(|b| b.unwrap().num_rows()).sum();
    assert_eq!(total, 0);

    assert_eq!(
        conn.get_option_string(OptionConnection::CurrentCatalog)
            .unwrap(),
        name
    );
    conn.set_option(OptionConnection::CurrentCatalog, name.clone().into())
        .unwrap();
    assert!(conn
        .set_option(OptionConnection::CurrentCatalog, "OTHER".into())
        .is_err());
}

#[test]
fn schemas_depth_filters_and_omits_tables() {
    let Some(mut conn) = connect() else { return };
    let user = current_user(&mut conn);
    let batch = objects(&conn, ObjectDepth::Schemas, Some(&user), None, None, None);
    let schemas = list_item(batch.column(1).as_ref(), 0).unwrap();
    assert_eq!(
        strings(&schemas, "db_schema_name"),
        std::slice::from_ref(&user)
    );
    assert!(schemas
        .column_by_name("db_schema_tables")
        .unwrap()
        .is_null(0));
}

#[test]
fn tables_depth_lists_types_without_columns() {
    let _guard = FIXTURE.lock().unwrap_or_else(|e| e.into_inner());
    let Some(mut conn) = connect() else { return };
    setup(&mut conn);
    let user = current_user(&mut conn);
    let batch = objects(
        &conn,
        ObjectDepth::Tables,
        Some(&user),
        Some("ORKIDEA_C_%"),
        None,
        None,
    );
    let tables = tables_of(&batch, &user).unwrap();
    let names = strings(&tables, "table_name");
    let types = strings(&tables, "table_type");
    let kind = |name: &str| types[names.iter().position(|n| n == name).unwrap()].clone();
    assert_eq!(kind("ORKIDEA_C_PARENT"), "TABLE");
    assert_eq!(kind("ORKIDEA_C_VIEW"), "VIEW");
    assert_eq!(kind("ORKIDEA_C_TEMP"), "TEMPORARY TABLE");
    let index = names.iter().position(|n| n == "ORKIDEA_C_PARENT").unwrap();
    assert!(tables
        .column_by_name("table_columns")
        .unwrap()
        .is_null(index));
    assert!(tables
        .column_by_name("table_constraints")
        .unwrap()
        .is_null(index));

    let views = objects(
        &conn,
        ObjectDepth::Tables,
        Some(&user),
        Some("ORKIDEA_C_%"),
        Some(vec!["VIEW"]),
        None,
    );
    assert_eq!(
        strings(&tables_of(&views, &user).unwrap(), "table_name"),
        ["ORKIDEA_C_VIEW"]
    );
}

#[test]
fn all_depth_reports_columns_and_constraints() {
    let _guard = FIXTURE.lock().unwrap_or_else(|e| e.into_inner());
    let Some(mut conn) = connect() else { return };
    setup(&mut conn);
    let user = current_user(&mut conn);
    let batch = objects(
        &conn,
        ObjectDepth::All,
        Some(&user),
        Some("ORKIDEA_C_%"),
        None,
        None,
    );
    let tables = tables_of(&batch, &user).unwrap();
    let parent = find(&tables, "table_name", "ORKIDEA_C_PARENT");
    let columns = list_item(
        tables.column_by_name("table_columns").unwrap().as_ref(),
        parent,
    )
    .unwrap();
    assert_eq!(
        strings(&columns, "column_name"),
        ["ID", "CODE", "REGION", "AMOUNT", "DOUBLED", "CREATED"]
    );
    let i16_at = |name: &str, row: usize| {
        let c = columns
            .column_by_name(name)
            .unwrap()
            .as_primitive::<Int16Type>();
        (!c.is_null(row)).then(|| c.value(row))
    };
    let i32_at = |name: &str, row: usize| {
        let c = columns
            .column_by_name(name)
            .unwrap()
            .as_primitive::<Int32Type>();
        (!c.is_null(row)).then(|| c.value(row))
    };
    let str_at = |name: &str, row: usize| {
        let c = columns.column_by_name(name).unwrap().as_string::<i32>();
        (!c.is_null(row)).then(|| c.value(row).to_string())
    };
    let bool_at = |name: &str, row: usize| {
        columns
            .column_by_name(name)
            .unwrap()
            .as_boolean()
            .value(row)
    };
    // ID: NUMBER(10) identity, part of the primary key.
    assert_eq!(i32_at("ordinal_position", 0), Some(1));
    assert_eq!(i16_at("xdbc_data_type", 0), Some(3));
    assert_eq!(i32_at("xdbc_column_size", 0), Some(10));
    assert_eq!(i16_at("xdbc_decimal_digits", 0), Some(0));
    assert!(bool_at("xdbc_is_autoincrement", 0));
    // CODE: VARCHAR2(20 CHAR) NOT NULL, with a comment.
    assert_eq!(i16_at("xdbc_data_type", 1), Some(12));
    assert_eq!(i32_at("xdbc_column_size", 1), Some(20));
    assert_eq!(i16_at("xdbc_nullable", 1), Some(0));
    assert_eq!(str_at("xdbc_is_nullable", 1).as_deref(), Some("NO"));
    assert_eq!(str_at("remarks", 1).as_deref(), Some("Business key"));
    // AMOUNT: default; DOUBLED: virtual; CREATED: TIMESTAMP(3).
    assert_eq!(str_at("xdbc_column_def", 3).as_deref(), Some("0"));
    assert!(bool_at("xdbc_is_generatedcolumn", 4));
    assert_eq!(str_at("xdbc_type_name", 5).as_deref(), Some("TIMESTAMP(3)"));
    assert_eq!(i16_at("xdbc_data_type", 5), Some(93));
    assert_eq!(i16_at("xdbc_decimal_digits", 5), Some(3));

    let constraints = list_item(
        tables.column_by_name("table_constraints").unwrap().as_ref(),
        parent,
    )
    .unwrap();
    let names = strings(&constraints, "constraint_name");
    let types = strings(&constraints, "constraint_type");
    let mut pairs: Vec<(String, String)> = names.into_iter().zip(types).collect();
    pairs.sort();
    assert_eq!(
        pairs,
        [
            ("ORKIDEA_C_PARENT_AMOUNT_CK".into(), "CHECK".into()),
            ("ORKIDEA_C_PARENT_CODE_UK".into(), "UNIQUE".into()),
            ("ORKIDEA_C_PARENT_PK".into(), "PRIMARY KEY".into()),
        ],
        "implicit NOT NULL checks must not be listed"
    );
    let pk = find(&constraints, "constraint_name", "ORKIDEA_C_PARENT_PK");
    let pk_columns = constraints
        .column_by_name("constraint_column_names")
        .unwrap()
        .as_list::<i32>()
        .value(pk);
    let pk_columns = pk_columns.as_string::<i32>();
    assert_eq!((pk_columns.value(0), pk_columns.value(1)), ("ID", "REGION"));

    // Foreign key: columns and referenced columns, in key order.
    let child = find(&tables, "table_name", "ORKIDEA_C_CHILD");
    let constraints = list_item(
        tables.column_by_name("table_constraints").unwrap().as_ref(),
        child,
    )
    .unwrap();
    let fk = find(&constraints, "constraint_name", "ORKIDEA_C_CHILD_FK");
    assert_eq!(strings(&constraints, "constraint_type")[fk], "FOREIGN KEY");
    let usage = list_item(
        constraints
            .column_by_name("constraint_column_usage")
            .unwrap()
            .as_ref(),
        fk,
    )
    .unwrap();
    assert_eq!(
        strings(&usage, "fk_table"),
        ["ORKIDEA_C_PARENT", "ORKIDEA_C_PARENT"]
    );
    assert_eq!(strings(&usage, "fk_column_name"), ["ID", "REGION"]);
    assert_eq!(
        strings(&usage, "fk_db_schema"),
        [user.clone(), user.clone()]
    );
    let pk = constraints
        .column_by_name("constraint_type")
        .unwrap()
        .as_string::<i32>()
        .iter()
        .position(|t| t == Some("PRIMARY KEY"))
        .unwrap();
    assert!(constraints
        .column_by_name("constraint_column_usage")
        .unwrap()
        .is_null(pk));

    // The column filter narrows columns but keeps the table.
    let batch = objects(
        &conn,
        ObjectDepth::All,
        Some(&user),
        Some("ORKIDEA_C_PARENT"),
        None,
        Some("CO%"),
    );
    let tables = tables_of(&batch, &user).unwrap();
    let columns = list_item(tables.column_by_name("table_columns").unwrap().as_ref(), 0).unwrap();
    assert_eq!(strings(&columns, "column_name"), ["CODE"]);
}

#[test]
fn statistics_come_from_the_optimizer() {
    let _guard = FIXTURE.lock().unwrap_or_else(|e| e.into_inner());
    let Some(mut conn) = connect() else { return };
    setup(&mut conn);
    let user = current_user(&mut conn);
    exec(
        &mut conn,
        "INSERT INTO orkidea_c_parent (code, region, amount) \
         SELECT 'c' || level, CASE WHEN MOD(level, 2) = 0 THEN 'EU' ELSE 'US' END, level FROM dual CONNECT BY level <= 3",
    );
    exec(
        &mut conn,
        "BEGIN DBMS_STATS.GATHER_TABLE_STATS(USER, 'ORKIDEA_C_PARENT'); END;",
    );
    let reader = conn
        .get_statistics(None, Some(&user), Some("ORKIDEA_C_PARENT"), true)
        .unwrap();
    let batch = reader.collect::<Result<Vec<_>, _>>().unwrap().remove(0);
    let schemas = list_item(batch.column(1).as_ref(), 0).unwrap();
    assert_eq!(strings(&schemas, "db_schema_name"), [user]);
    let stats = list_item(
        schemas
            .column_by_name("db_schema_statistics")
            .unwrap()
            .as_ref(),
        0,
    )
    .unwrap();
    let keys = stats
        .column_by_name("statistic_key")
        .unwrap()
        .as_primitive::<Int16Type>();
    let columns = stats
        .column_by_name("column_name")
        .unwrap()
        .as_string::<i32>();
    let values = stats.column_by_name("statistic_value").unwrap().as_union();
    let int_value = |row: usize| values.value(row).as_primitive::<Int64Type>().value(0);
    let lookup = |column: Option<&str>, key: i16| {
        (0..stats.len())
            .find(|&i| {
                keys.value(i) == key
                    && (if columns.is_null(i) {
                        None
                    } else {
                        Some(columns.value(i))
                    }) == column
            })
            .map(int_value)
    };
    assert_eq!(lookup(None, ADBC_STATISTIC_ROW_COUNT_KEY), Some(3));
    assert_eq!(
        lookup(Some("CODE"), ADBC_STATISTIC_DISTINCT_COUNT_KEY),
        Some(3)
    );
    assert_eq!(
        lookup(Some("CREATED"), ADBC_STATISTIC_NULL_COUNT_KEY),
        Some(3)
    );
    let approximate = stats
        .column_by_name("statistic_is_approximate")
        .unwrap()
        .as_boolean();
    assert!((0..stats.len()).all(|i| approximate.value(i)));
}

